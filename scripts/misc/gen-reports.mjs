import { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableCell, TableRow, WidthType, AlignmentType, BorderStyle, TableLayoutType } from 'docx';
import fs from 'fs';

function h1(text) { return new Paragraph({ text, heading: HeadingLevel.HEADING_1, spacing: { before: 360, after: 120 } }); }
function h2(text) { return new Paragraph({ text, heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 100 } }); }
function p(text) { return new Paragraph({ children: [new TextRun({ text, size: 21 })], spacing: { after: 80, line: 360 } }); }
function bold(text) { return new Paragraph({ children: [new TextRun({ text, size: 21, bold: true })], spacing: { after: 60 } }); }
function makeTable(headers, rows) {
  const allRows = [headers, ...rows];
  const tableRows = allRows.map((row, ri) => new TableRow({ children: row.map(cell => new TableCell({
    children: [new Paragraph({ children: [new TextRun({ text: String(cell), size: 18, bold: ri === 0 })] })],
    width: { size: 100 / row.length, type: WidthType.PERCENTAGE },
  })) }));
  return [new Table({ rows: tableRows, width: { size: 100, type: WidthType.PERCENTAGE }, layout: TableLayoutType.FIXED }), new Paragraph({ spacing: { after: 120 }, children: [] })];
}

async function buildDoc(title, buildFn) {
  const children = [];
  children.push(new Paragraph({ text: title, heading: HeadingLevel.TITLE, alignment: AlignmentType.CENTER, spacing: { after: 120 } }));
  children.push(new Paragraph({ children: [new TextRun({ text: '三江科创院 · 智慧农业创新中心', size: 22, color: '4472C4' })], alignment: AlignmentType.CENTER }));
  children.push(new Paragraph({ children: [new TextRun({ text: '2026-05-22 | 湖南益阳桃江', size: 20, color: '888888' })], alignment: AlignmentType.CENTER, spacing: { after: 360 } }));
  buildFn(children);
  const doc = new Document({ sections: [{ children }] });
  return await Packer.toBuffer(doc);
}

